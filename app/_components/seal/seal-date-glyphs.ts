/**
 * 竖排日期章笔画：每字一格，格高按 DATE_W 加权；月组与日组之间一道横界格。
 * 样张参数固定 fw=1.9、sw=1.35、gap=1.0、sep=2.4，返回 { strokes, gridY }。
 */
export function dateStrokesV(month: number, day: number): { strokes: number[][][]; gridY: number } {
  const [x0, y0, x1, y1] = DATEV;
  const fw = 1.9;
  const sw = 1.35;
  const gap = 1.0;
  const sep = 2.4;
  const ins = fw / 2 + gap + sw / 2;
  const X0 = x0 + ins;
  const X1 = x1 - ins;
  const Y0 = y0 + ins;
  const Y1 = y1 - ins;
  const g1 = cnNum(month, "月");
  const g2 = cnNum(day, "日");
  const chars = [...g1, ...g2];
  const pad = 1.5 + sw * 0.45; // 格内上下留白（和字距一起，让笔画不粘连）
  const tot = chars.reduce((a, c) => a + (DATE_W[c] ?? 1), 0);
  const H = Y1 - Y0 - sep; // 界格让出 sep
  const unit = H / tot;
  const out: number[][][] = [];
  let y = Y0;
  let gridY = 0; // 界格横线 y（月组与日组之间）
  for (let i = 0; i < chars.length; i++) {
    const ch = chars[i];
    const h = (DATE_W[ch] ?? 1) * unit;
    const st = lxChar(ch);
    const [bx0, by0, bx1, by1] = bbox(st);
    const chH = Math.max(h - pad, 0.5);
    // 横向吃满；只有一横的「一」按中线放
    if (by1 - by0 < 3) {
      for (const s of st) {
        out.push(s.map(([px]) => [X0 + ((px - bx0) / (bx1 - bx0)) * (X1 - X0), y + h / 2] as [number, number]));
      }
    } else {
      out.push(...place(st, [X0, y + pad / 2, X1, y + pad / 2 + chH]));
    }
    y += h;
    if (i === g1.length - 1) {
      gridY = y + sep / 2;
      y += sep;
    }
  }
  return { strokes: out, gridY };
}

/** 日期章印文 path d：所有笔画过 poly_d（平滑）后拼接 */
export function dateGlyphD(month: number, day: number): string {
  return dateStrokesV(month, day).strokes.map((s) => polyD(s, true)).join("");
}

/** 日期章界格 path d：M<x0> <y>H<x1> */
export function dateGridD(gridY: number): string {
  return `M${fmt(DATEV[0])} ${fmt(gridY)}H${fmt(DATEV[2])}`;
}
