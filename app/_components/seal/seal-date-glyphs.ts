// ---------- pathutil：fmt / poly_d ----------

/** 半格判据：第三位小数起恰为 5 后全零（双精度小数展开必终止，50 位足够分辨） */
const TIE_REST = "5" + "0".repeat(47);

/**
 * 数值格式化：.2f 再抹尾零（-0 / 空串归 0），与 Python f"{v:.2f}" 对齐。
 * 修约差异只在恰好半格（如 19.625）：Python 取偶数，JS toFixed 取较大者；
 * 双精度是二进分数、小数展开必终止，用 toFixed(50) 的精确展开手动判半格。
 */
function fmt(v: number): string {
  const a = Math.abs(v);
  const frac = a.toFixed(50).split(".")[1] ?? "";
  const int = Math.trunc(a);
  let cents = int * 100 + Number(frac.slice(0, 2));
  const rest = frac.slice(2, 52);
  if (rest === TIE_REST) {
    if (cents % 2 === 1) cents += 1;
  } else if (rest > TIE_REST) {
    cents += 1;
  }
  if (cents === 0) return "0";
  const body = String(cents / 100);
  return v < 0 ? "-" + body : body;
}

/**
 * 折线 → 平滑 SVG 路径（Catmull-Rom 转三次贝塞尔）。与 pathutil.poly_d 逐分支对应：
 * 单点 M…h0；两点或不平滑 M…L…；其余按 Catmull-Rom 控制点 C…。
 */
function polyD(pts: number[][], smooth = true, closed = false): string {
  if (pts.length === 1) {
    const [x, y] = pts[0];
    return `M${fmt(x)} ${fmt(y)}h0`;
  }
  const p =
    closed && (pts[0][0] !== pts[pts.length - 1][0] || pts[0][1] !== pts[pts.length - 1][1])
      ? [...pts, pts[0]]
      : pts;
  if (!smooth || p.length === 2) {
    return "M" + p.map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join("L");
  }
  const n = p.length;
  let d = `M${fmt(p[0][0])} ${fmt(p[0][1])}`;
  for (let i = 0; i < n - 1; i++) {
    const p0 = i > 0 ? p[i - 1] : closed ? p[n - 2] : p[i];
    const p1 = p[i];
    const p2 = p[i + 1];
    const p3 = i + 2 < n ? p[i + 2] : closed ? p[1] : p2;
    const c1x = p1[0] + (p2[0] - p0[0]) / 6;
    const c1y = p1[1] + (p2[1] - p0[1]) / 6;
    const c2x = p2[0] - (p3[0] - p1[0]) / 6;
    const c2y = p2[1] - (p3[1] - p1[1]) / 6;
    d += `C${fmt(c1x)} ${fmt(c1y)} ${fmt(c2x)} ${fmt(c2y)} ${fmt(p2[0])} ${fmt(p2[1])}`;
  }
  return d;
}

// ---------- seals.py：bbox / place / cn_num / lx_char ----------

/** 所有笔画的包围盒 (x0,y0,x1,y1) */
function bbox(strokes: number[][][]): [number, number, number, number] {
  let x0 = Infinity;
  let y0 = Infinity;
  let x1 = -Infinity;
  let y1 = -Infinity;
  for (const s of strokes) {
    for (const [x, y] of s) {
      if (x < x0) x0 = x;
      if (x > x1) x1 = x;
      if (y < y0) y0 = y;
      if (y > y1) y1 = y;
    }
  }
  return [x0, y0, x1, y1];
}

/** 把字形的包围盒整体放进 box（等比平移缩放，除零兜底同 Python 的 or 1） */
function place(strokes: number[][][], box: [number, number, number, number]): number[][][] {
  const [x0, y0, x1, y1] = bbox(strokes);
  const [X0, Y0, X1, Y1] = box;
  const dx = x1 - x0 || 1;
  const dy = y1 - y0 || 1;
  return strokes.map((s) =>
    s.map(([x, y]) => [X0 + ((x - x0) / dx) * (X1 - X0), Y0 + ((y - y0) / dy) * (Y1 - Y0)] as [number, number]),
  );
}

const NUM = "〇一二三四五六七八九";

/** 日期用的中文数字（十、廿、卅记数），加单位（月 / 日） */
function cnNum(n: number, unit: string): string[] {
  let s: string[];
  if (n <= 10) s = ["一二三四五六七八九十"[n - 1]];
  else if (n < 20) s = ["十", NUM[n - 10]];
  else if (n === 20) s = ["廿"];
  else if (n < 30) s = ["廿", NUM[n - 20]];
  else if (n === 30) s = ["卅"];
  else s = ["卅", NUM[n - 30]];
  return [...s, unit];
}

/** 取字形中心线；卅 霞鹜篆书没有，照廿（两竖一横、底部圆转相连）补成三竖，笔势、横位、底弧照廿 */
function lxChar(ch: string): number[][][] {
  if (ch === "卅") {
    const U: [number, number][] = [
      [22, 36.5], [22.2, 63.6], [23.4, 70.4], [25.6, 75.6], [29.5, 79.6], [35.5, 82.2],
      [50, 83], [64.5, 82.2], [70.5, 79.6], [74.4, 75.6], [76.6, 70.4], [77.8, 63.6], [78, 36.5],
    ];
    return [
      [[8, 36], [92, 36]],
      [[22, 15], [22, 36.5]],
      [[78, 15], [78, 36.5]],
      [[50, 15], [50, 83]],
      U,
    ];
  }
  return LX[ch];
}

