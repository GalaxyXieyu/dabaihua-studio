def apply_edits(text: str, edits: list[Edit]) -> str:
    for edit in edits:
        count = text.count(edit.old)
        if count != 1:
            raise RuntimeError(f"{edit.location}: expected one match, found {count}")
        text = text.replace(edit.old, edit.new, 1)
    return text


def write_diff(path: Path, edits: list[Edit]) -> None:
    lines = ["# Aige 14 标点审校记录", "", f"共 {len(edits)} 组语意修改。", ""]
    for index, edit in enumerate(edits, 1):
        old = edit.old.replace("\n\n", " / ")
        new = edit.new.replace("\n\n", " / ")
        lines.extend([
            f"## {index:02d} · {edit.location}",
            "",
            f"- 原文：{old}",
            f"- 修改：{new}",
            f"- 依据：{edit.rule}",
            "",
        ])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("punctuation", type=Path)
    parser.add_argument("diff", type=Path)
    args = parser.parse_args()
    source = args.source.read_text(encoding="utf-8")
    punctuated = apply_edits(source, PUNCTUATION_EDITS)
    args.punctuation.write_text(punctuated, encoding="utf-8")
    write_diff(args.diff, PUNCTUATION_EDITS)
    print(f"punctuation groups: {len(PUNCTUATION_EDITS)}")
    print(f"wrote: {args.punctuation}")
    print(f"wrote: {args.diff}")


if __name__ == "__main__":
    main()
